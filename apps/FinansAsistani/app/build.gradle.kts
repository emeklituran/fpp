// İsteğe bağlı imzalama: proje kökünde keystore.properties varsa release APK bu anahtarla imzalanır.
// Yoksa APK yine kurulabilir olsun diye Android debug anahtarı kullanılır.
val keystoreProperties = Properties().apply {
    val file = rootProject.file("keystore.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}
val hasReleaseKeystore = listOf("storeFile", "storePassword", "keyAlias", "keyPassword")
    .all { !keystoreProperties.getProperty(it).isNullOrBlank() }

android {
    namespace = "com.fpp.finansasistani"
    compileSdk = 36

    defaultConfig {
        applicationId = "com.fpp.finansasistani"
        // Android 8.0+: java.time API'leri yerleşik, cihazların ~%97'si kapsanır.
        minSdk = 26
        // Galaxy S25: Android 15 (API 35) ile çıktı, Android 16 (API 36) güncellemesi aldı.
        targetSdk = 36
        versionCode = 1
        versionName = "1.0.0"
        // Yalnızca Türkçe kaynaklar paketlenir (APK küçülür).
        @Suppress("DEPRECATION")
        resourceConfigurations += listOf("tr")
    }

    signingConfigs {
        if (hasReleaseKeystore) {
            create("release") {
                storeFile = rootProject.file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro",
            )
            signingConfig = if (hasReleaseKeystore) {
                signingConfigs.getByName("release")
            } else {
                signingConfigs.getByName("debug")
            }
        }
        debug {
            isMinifyEnabled = false
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    packaging {
        resources {
            excludes += "/META-INF/{AL2.0,LGPL2.1}"
            excludes += "/META-INF/*.version"
            excludes += "DebugProbesKt.bin"
        }
    }

    // Google'a özel, şifreli bağımlılık meta verisi APK'ya eklenmez.
    dependenciesInfo {
        includeInApk = false
        includeInBundle = false
    }

    lint {
        abortOnError = true
        checkReleaseBuilds = true
    }
}

